"""BRIEF_RP §9: checkpoint_tier map and the column on Phase R tables.

The map is tested strictly. Committed tables owned by other streams are regenerated by generators that may not call
`annotate` yet, so a missing / stale column or an unknown reader there is a WARNING (run
`python -m projects.g_agreement.r_bench.checkpoint_tier --apply`); only BRIEF_RP's own tables (results/g_agreement/rp/)
fail the test.

Run: ``.venv/bin/python -m pytest projects/g_agreement/tests/test_checkpoint_tier.py -q``
"""
from __future__ import annotations

import sys
import warnings
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

import pandas as pd  # noqa: E402

from projects.g_agreement.r_bench import checkpoint_tier as T  # noqa: E402

OWN = "results/g_agreement/rp/"


def test_tiers_by_rule():
    assert T.tier("olens") == T.tier("jlens@42") == T.tier("nla@42") == T.tier("skip_a") == "community"
    assert T.tier("olens_trueL") == "community"
    assert T.tier("AO@21 chat") == T.tier("ao_yn_noact") == T.tier("AO no-act (text)") == "standard"
    assert T.tier("sae:sae16:k128") == T.tier("sae16 k16") == "standard"
    assert T.tier("q8_ao") == T.tier("q32_ao") == T.tier("q8b_ao") == T.tier("q27_ao") == T.tier("q27_ao_base") == "standard"
    for k in ("probe(512)", "probe LR(512)", "lr", "mm", "logit lens@20", "logit_lens_rot", "rot. readout",
              "prompt-only", "model_ft"):
        assert T.tier(k) == "none", k
    assert T.tier("something_new") == "unknown"


def test_aggregates():
    assert T.tier("['ao', 'ao_yn', 'llens']") == "standard"
    assert T.tier("['olens', 'ao']") == "mixed"
    assert T.tier("all@raw", "standard") == "standard"
    assert T.tier("H7-G", "community") == "community"
    assert T.tier("all") == "unknown"


def test_annotate_long_and_single_reader():
    df = pd.DataFrame({"dataset": ["a", "b"], "reader": ["olens", "logit_lens"]})
    assert T.annotate(df)[T.COL].tolist() == ["community", "none"]
    one = pd.DataFrame({"dataset": ["a"], "auc_act": [0.7]})
    assert T.annotate(one, "results/g_agreement/r/text_arm.csv")[T.COL].tolist() == ["community"]
    other = pd.DataFrame({"dataset": ["a"], "x": [1]})
    assert T.annotate(other, "results/g_agreement/r/anything.csv") is other   # unclassifiable: unchanged


def test_committed_tables():
    problems = T.apply(check_only=True)
    own = [p for p in problems if p.startswith(OWN)]
    others = [p for p in problems if not p.startswith(OWN)]
    if others:
        warnings.warn("checkpoint_tier: run `python -m projects.g_agreement.r_bench.checkpoint_tier --apply`:\n  "
                      + "\n  ".join(others))
    assert own == []
