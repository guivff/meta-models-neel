"""80 GB GPU stock across RunPod datacenters (PODS.md rule 8). Mac-side; read-only GraphQL via ~/repl/tools/runpod_api.sh.

    python3 results/g_agreement/r/pod_tools/ws2_stock.py            # check now, append to the log, rewrite the list
    python3 results/g_agreement/r/pod_tools/ws2_stock.py --quiet    # print only the ranked "<dc> <gpuTypeId>" lines

Every check appends one row to results/g_agreement/r/pod_stock.jsonl (also when nothing is in stock) and rewrites
results/g_agreement/r/POD_STOCK.md, the list of datacenters that have had 80 GB stock (first / last seen, times seen).
Candidates are ranked H100 first (rule 7.4), then A100-80GB, then H200 and the larger cards; MIG slices and AMD are
excluded. Exit 0 if any candidate is in stock, 3 if none, 2 if the API call failed.

The API's stock flag is advisory: a deploy can still fail with "no instances"; the deploy result is the ground truth, so
rule 8's launcher logs its deploy attempts too (see PODS.md rule 8).
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parents[4]
LOG = REPO / "results" / "g_agreement" / "r" / "pod_stock.jsonl"
MD = REPO / "results" / "g_agreement" / "r" / "POD_STOCK.md"
API = Path.home() / "repl" / "tools" / "runpod_api.sh"
VOLUME_DC = "EUR-IS-3"  # network volume w9182om1pd (mats-minis)

# Rank order: rule 7.4 prefers the H100; H200 and larger cards are fallbacks.
# Deliberate config, not a derived list (GUARDS.md rule 1 review, WS2 2026-10-20): this is the ranking policy itself; no module
# or data defines it. A card not named here is never a candidate (fails toward "not in stock").
RANK = [
    "NVIDIA H100 80GB HBM3", "NVIDIA H100 NVL", "NVIDIA H100 PCIe",
    "NVIDIA A100-SXM4-80GB", "NVIDIA A100 80GB PCIe",
    "NVIDIA H200", "NVIDIA H200 NVL",
    "NVIDIA RTX PRO 6000 Blackwell Server Edition", "NVIDIA RTX PRO 6000 Blackwell Workstation Edition",
    "NVIDIA B200",
]
QUERY = "query { dataCenters { id name location gpuAvailability { gpuTypeId gpuTypeDisplayName stockStatus available } } }"


def fetch() -> dict:
    out = subprocess.run(["bash", str(API), QUERY], capture_output=True, text=True, timeout=120)
    return json.loads(out.stdout)


def candidates(resp: dict) -> list[dict]:
    """In-stock 80 GB-class GPUs, ranked: volume datacenter first within a GPU type, then by rank and stock level."""
    level = {"High": 0, "Medium": 1, "Low": 2}
    rows = []
    for dc in resp["data"]["dataCenters"]:
        for g in dc.get("gpuAvailability") or []:
            gid = g.get("gpuTypeId") or ""
            if gid not in RANK or "MIG" in gid or not (g.get("available") or g.get("stockStatus")):
                continue
            rows.append({"dc": dc["id"], "location": dc.get("location"), "gpu": gid,
                         "display": g.get("gpuTypeDisplayName"), "stock": g.get("stockStatus")})
    rows.sort(key=lambda r: (RANK.index(r["gpu"]), r["dc"] != VOLUME_DC, level.get(r["stock"] or "", 3), r["dc"]))
    return rows


def append_log(rows: list[dict], n_dc: int, log: Path, ts: str) -> None:
    log.parent.mkdir(parents=True, exist_ok=True)
    with log.open("a") as f:
        f.write(json.dumps({"ts": ts, "n_datacenters": n_dc, "in_stock": rows}) + "\n")


def write_list(log: Path, md: Path) -> None:
    seen: dict[tuple[str, str], dict] = {}
    checks, last = 0, None
    for line in log.read_text().splitlines():
        if not line.strip():
            continue
        r = json.loads(line)
        checks, last = checks + 1, r["ts"]
        for c in r["in_stock"]:
            k = (c["dc"], c["gpu"])
            s = seen.setdefault(k, {"location": c.get("location"), "first": r["ts"], "n": 0})
            s.update(last=r["ts"], stock=c.get("stock"), display=c.get("display"), n=s["n"] + 1)
    lines = ["# 80 GB GPU stock by datacenter (PODS.md rule 8)", "",
             f"Generated by `pod_tools/ws2_stock.py` from `pod_stock.jsonl`: {checks} checks, last {last}. "
             "Advisory API flag; a deploy can still fail.", "",
             "| datacenter | location | GPU | first seen | last seen | times seen | last stock |", "|---|---|---|---|---|---|---|"]
    for (dc, gpu), s in sorted(seen.items(), key=lambda kv: (RANK.index(kv[0][1]), kv[0][0])):
        lines.append(f"| {dc}{' (volume)' if dc == VOLUME_DC else ''} | {s['location']} | {s['display'] or gpu} | "
                     f"{s['first']} | {s['last']} | {s['n']} | {s['stock']} |")
    if not seen:
        lines.append("| none yet | | | | | | |")
    md.write_text("\n".join(lines) + "\n")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--from-json", help="read the API response from a file (tests) instead of calling RunPod")
    ap.add_argument("--log", default=str(LOG))
    ap.add_argument("--md", default=str(MD))
    ap.add_argument("--quiet", action="store_true")
    a = ap.parse_args(argv)
    try:
        resp = json.loads(Path(a.from_json).read_text()) if a.from_json else fetch()
        n_dc = len(resp["data"]["dataCenters"])
    except Exception as e:  # noqa: BLE001 — any API failure is "unknown", never "in stock"
        print(f"stock check failed: {type(e).__name__}", file=sys.stderr)
        return 2
    ts = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    rows = candidates(resp)
    append_log(rows, n_dc, Path(a.log), ts)
    write_list(Path(a.log), Path(a.md))
    for r in rows:
        print(f"{r['dc']} {r['gpu']}" if a.quiet else f"{ts} {r['dc']:<10} {r['display'] or r['gpu']:<16} {r['stock']}")
    if not rows and not a.quiet:
        print(f"{ts} no 80 GB stock in {n_dc} datacenters")
    return 0 if rows else 3


if __name__ == "__main__":
    sys.exit(main())
