"""Build and verify E39's isolated Triton overlay; never run a model or optimizer."""
from __future__ import annotations

import argparse
import hashlib
import importlib
import importlib.metadata as metadata
import importlib.util
import json
import math
from pathlib import Path
import platform
import subprocess
import sys
import sysconfig
import time

HERE = Path(__file__).resolve().parent
READINESS_DEADLINE = 1793228340  # Programme cutoff: 2026-10-28 22:59 UTC. E28 noon deadline was run-specific.
INHERITED = ('torch', 'transformers', 'fla', 'causal_conv1d', 'peft')
MODULES = (*INHERITED, 'triton')
DIST_ALIASES = {'fla': ('flash-linear-attention', 'fla-core'), 'causal_conv1d': ('causal-conv1d',)}


class EnvironmentNotReady(RuntimeError):
    """A terminal stop for this attempt; no automatic environment or science retry."""


def sha(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as f:
        for block in iter(lambda: f.read(8 * 1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def read(path):
    return json.loads(Path(path).read_text())


def write_new(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('x') as f:
        json.dump(value, f, indent=2, sort_keys=True, allow_nan=False)
        f.write('\n')


def tree_manifest(root):
    """Hash actual source/native-library bytes, ignoring only generated bytecode."""
    root = Path(root).resolve()
    paths = [root] if root.is_file() else sorted(p for p in root.rglob('*') if p.is_file())
    files = {}
    for p in paths:
        relative = p.name if root.is_file() else p.relative_to(root).as_posix()
        if '__pycache__' in p.parts or '.git' in p.parts or p.suffix in ('.pyc', '.pyo'):
            continue
        files[relative] = sha(p)
    if not files:
        raise EnvironmentNotReady('empty installed module tree')
    digest = hashlib.sha256(json.dumps(files, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    return {'root': str(root), 'tree_sha256': digest, 'files': files}


def module_snapshot(name, optional=False):
    spec = importlib.util.find_spec(name)
    if spec is None or spec.origin is None:
        if optional:
            return None
        raise EnvironmentNotReady('required inherited module absent: ' + name)
    distribution_names = metadata.packages_distributions().get(name, [])
    candidates = distribution_names or list(DIST_ALIASES.get(name, (name,)))
    distributions = []
    for candidate in candidates:
        try:
            dist = metadata.distribution(candidate)
        except metadata.PackageNotFoundError:
            continue
        hashes = {}
        for filename in ('METADATA', 'RECORD', 'direct_url.json'):
            value = dist.read_text(filename)
            if value is not None:
                hashes[filename] = hashlib.sha256(value.encode()).hexdigest()
        distributions.append({'name': dist.metadata['Name'], 'version': dist.version, 'metadata_sha256': hashes})
    if not distributions:
        raise EnvironmentNotReady('cannot pin actual distribution version for: ' + name)
    origin = Path(spec.origin).resolve()
    root = origin.parent if spec.submodule_search_locations is not None else origin
    return {'module': name, 'origin': str(origin), 'distributions': sorted(distributions, key=lambda d: d['name']),
            **tree_manifest(root)}


def package_paths():
    # A venv can inherit global dist-packages. Keep the actual interpreter order,
    # excluding CWD/project/PYTHONPATH directories that are not package roots.
    roots = []
    for raw in sys.path:
        p = Path(raw).resolve()
        if p.name in ('site-packages', 'dist-packages') and p.is_dir() and str(p) not in roots:
            roots.append(str(p))
    if not roots:
        raise EnvironmentNotReady('no actual inherited package roots found')
    return roots


def snapshot(require_triton=False):
    return {'schema': 'E39_INSTALLED_ENV_SNAPSHOT_v1', 'python_version': platform.python_version(),
        'executable': str(Path(sys.executable).absolute()), 'executable_sha256': sha(Path(sys.executable).resolve()),
        'prefix': sys.prefix, 'base_prefix': sys.base_prefix,
        'package_paths': package_paths(),
        'modules': {name: module_snapshot(name, optional=name == 'triton' and not require_triton) for name in MODULES}}


def snapshot_identity(value):
    return {k: value[k] for k in ('python_version', 'executable_sha256', 'prefix', 'modules')}


def validate_preserved(before, after):
    if before['python_version'] != after['python_version'] or before['executable_sha256'] != after['executable_sha256']:
        raise EnvironmentNotReady('overlay changed the inherited Python interpreter')
    for name in INHERITED:
        if before['modules'][name] != after['modules'][name]:
            raise EnvironmentNotReady('inherited package changed: ' + name)
    triton = after['modules'].get('triton')
    if triton is None or {x['version'] for x in triton['distributions']} != {'3.7.1'}:
        raise EnvironmentNotReady('exact approved Triton 3.7.1 required')


def import_probe():
    """Imports only: neither a CUDA kernel nor a model forward is executed."""
    modules = {name: importlib.import_module(name) for name in MODULES}
    importlib.import_module('fla.ops.gated_delta_rule.chunk')
    root = Path(modules['fla'].__file__).resolve().parent
    backward = {p.relative_to(root).as_posix(): sha(p) for p in root.rglob('*.py')
                if 'chunk_bwd_dqkwg' in p.read_text(errors='replace')}
    if not backward:
        raise EnvironmentNotReady('required FLA chunk_bwd_dqkwg backward source not found')
    return {'status': 'IMPORTS_PASS', 'backward_source_files': backward,
            'torch_version': modules['torch'].__version__, 'torch_cuda_version': modules['torch'].version.cuda,
            'cuda_available': bool(modules['torch'].cuda.is_available()), 'model_forwards': 0,
            'optimizer_steps': 0, 'cuda_backward_verified': False}


def run_python(python, args):
    value = subprocess.run([str(python), *map(str, args)], capture_output=True, text=True)
    if value.returncode:
        # Do not print pip/process stderr: inherited configuration can contain credentials.
        raise EnvironmentNotReady('isolated environment subprocess failed; exit=' + str(value.returncode))


def build_overlay(base_python, overlay, manifest, now=time.time):
    base_python, overlay, manifest = Path(base_python), Path(overlay), Path(manifest)
    if now() > READINESS_DEADLINE:
        raise EnvironmentNotReady('readiness deadline passed: NOT_RUN_ENVIRONMENT')
    if not base_python.is_file() or base_python.parent.parent.resolve() != Path('/weights/venv-kernels').resolve():
        raise EnvironmentNotReady('approved /weights/venv-kernels base interpreter required')
    if (not overlay.resolve().is_relative_to(Path('/tmp').resolve()) or not overlay.name.startswith('e39-')
            or overlay.exists() or manifest.exists()):
        raise EnvironmentNotReady('fresh pod-local /tmp/e39-* overlay and immutable manifest required')
    overlay.parent.mkdir(parents=True, exist_ok=True)
    work = overlay.parent / (overlay.name + '-evidence')
    work.mkdir(exist_ok=False)
    before_path = work / 'BASE_SNAPSHOT.json'
    run_python(base_python, [__file__, 'snapshot', '--out', before_path])
    before = read(before_path)
    run_python(base_python, ['-m', 'venv', str(overlay)])
    python = overlay / 'bin/python'
    path_file = work / 'OVERLAY_PATHS.json'
    run_python(python, ['-c', "import json,sysconfig,pathlib;pathlib.Path(__import__('sys').argv[1]).write_text(json.dumps({'purelib':sysconfig.get_path('purelib')}))", path_file])
    site_packages = Path(read(path_file)['purelib'])
    if not site_packages.resolve().is_relative_to(overlay.resolve()):
        raise EnvironmentNotReady('overlay package directory escaped its fresh environment')
    inherited_path = site_packages / 'e39_inherited_base.pth'
    inherited_path.write_text(''.join(p + '\n' for p in before['package_paths']))
    requirements = HERE / 'OVERLAY_REQUIREMENTS.txt'
    run_python(python, ['-m', 'pip', '--isolated', '--disable-pip-version-check', 'install',
        '--index-url', 'https://pypi.org/simple', '--no-deps', '--ignore-installed', '--require-hashes',
        '--only-binary=:all:', '-r', requirements])
    after_path, probe_path = work / 'OVERLAY_SNAPSHOT.json', work / 'IMPORT_PROBE.json'
    run_python(python, [__file__, 'snapshot', '--require-triton', '--out', after_path])
    run_python(python, [__file__, 'probe', '--out', probe_path])
    after, probe = read(after_path), read(probe_path)
    validate_preserved(before, after)
    if not probe['cuda_available']:
        raise EnvironmentNotReady('CUDA is unavailable on the intended training pod')
    if now() > READINESS_DEADLINE:
        raise EnvironmentNotReady('readiness deadline elapsed during overlay preparation')
    result = {'schema': 'E39_TRAINING_ENVIRONMENT_v1', 'status': 'PREPARED_FROZEN',
        'prepared_epoch': now(), 'readiness_deadline_epoch': READINESS_DEADLINE,
        'base_python': str(base_python), 'overlay_python': str(python),
        'requirements_sha256': sha(requirements), 'inherited_path_file': str(inherited_path),
        'inherited_path_sha256': sha(inherited_path), 'base_snapshot': before, 'overlay_snapshot': after,
        'import_probe': probe, 'only_installed_distribution': 'triton==3.7.1',
        'model_forwards': 0, 'optimizer_steps': 0, 'cuda_backward_verified': False,
        'real_readiness_requirement': 'one finite actual CUDA train_step after the registered pretraining parity gate, completed before deadline'}
    write_new(manifest, result)
    return result


def validate_prepared(value, current, now):
    if (value.get('schema') != 'E39_TRAINING_ENVIRONMENT_v1' or value.get('status') != 'PREPARED_FROZEN'
            or value.get('readiness_deadline_epoch') != READINESS_DEADLINE
            or value.get('cuda_backward_verified') is not False
            or value.get('model_forwards') != 0 or value.get('optimizer_steps') != 0):
        raise EnvironmentNotReady('pre-forward frozen overlay manifest required')
    prepared = value.get('prepared_epoch')
    if type(prepared) not in (int, float) or not math.isfinite(prepared) or not 0 <= prepared <= now <= READINESS_DEADLINE:
        raise EnvironmentNotReady('real training readiness cannot be established after its deadline')
    validate_preserved(value['base_snapshot'], value['overlay_snapshot'])
    if snapshot_identity(value['overlay_snapshot']) != snapshot_identity(current):
        raise EnvironmentNotReady('installed environment changed after its freeze')


def verify_manifest(path, expected_sha256, now=time.time):
    path = Path(path)
    if not path.is_file() or sha(path) != expected_sha256:
        raise EnvironmentNotReady('assigned environment manifest missing or changed')
    value = read(path)
    if sha(HERE / 'OVERLAY_REQUIREMENTS.txt') != value.get('requirements_sha256'):
        raise EnvironmentNotReady('reviewed overlay requirements changed')
    if sha(value['inherited_path_file']) != value.get('inherited_path_sha256'):
        raise EnvironmentNotReady('base environment inheritance changed')
    validate_prepared(value, snapshot(require_triton=True), now())
    if Path(sys.executable).absolute() != Path(value['overlay_python']).absolute():
        raise EnvironmentNotReady('worker must use the pinned overlay interpreter')
    return value


def runtime_ready(diagnostics, device, completed_epoch, environment_sha256, parity_sha256):
    if (str(device).split(':')[0] != 'cuda' or type(completed_epoch) not in (int, float)
            or not math.isfinite(completed_epoch) or not 0 < completed_epoch <= READINESS_DEADLINE
            or not diagnostics.get('finite_loss') or not diagnostics.get('finite_gradients')
            or not diagnostics.get('frozen_parameter_grads_none')):
        raise EnvironmentNotReady('actual finite CUDA backward before deadline required')
    return {'schema': 'E39_TRAINING_ENV_RUNTIME_v1', 'status': 'TRAINING_ENVIRONMENT_READY',
        'device': 'cuda', 'real_cuda_backward': True, 'completed_epoch': completed_epoch,
        'readiness_deadline_epoch': READINESS_DEADLINE, 'finite_loss': True, 'finite_gradients': True,
        'optimizer_steps_in_readiness': 1, 'fresh_lora_only': True,
        'environment_manifest_sha256': environment_sha256, 'parity_result_sha256': parity_sha256,
        'cuda_backward_verified': True}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    sub = p.add_subparsers(dest='command', required=True)
    build = sub.add_parser('prepare')
    build.add_argument('--base-python', type=Path, default=Path('/weights/venv-kernels/bin/python'))
    build.add_argument('--overlay', type=Path, required=True)
    build.add_argument('--manifest', type=Path, required=True)
    snap = sub.add_parser('snapshot')
    snap.add_argument('--out', type=Path, required=True)
    snap.add_argument('--require-triton', action='store_true')
    probe = sub.add_parser('probe')
    probe.add_argument('--out', type=Path, required=True)
    a = p.parse_args()
    try:
        if a.command == 'prepare':
            build_overlay(a.base_python, a.overlay, a.manifest)
            print('PREPARED_FROZEN; actual CUDA backward remains unverified')
        elif a.command == 'snapshot':
            write_new(a.out, snapshot(a.require_triton))
        else:
            write_new(a.out, import_probe())
    except (EnvironmentNotReady, ImportError, OSError):
        print('NOT_RUN_ENVIRONMENT')
        return 2
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
