"""Render share/inventory/experiments_index.json as the one-line-per-experiment table in share/EXPERIMENTS.md.

    python3 share/build_index.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROGRAMMES = [("early", "G, X, Y, Z, W/V, S/F2 phases (4–21 Oct)", "BRIEF.md … BRIEF_S.md, PREREG_WV.md"),
              ("blindspot", "Blind-spot map W1–W12 and screens S1–S5 (23–24 Oct)", "BRIEF_BLINDSPOT.md §70–§104"),
              ("understand", "Understanding the blind spot: E1–E51, Q1/Q2 (24–26 Oct)", "BRIEF_UNDERSTAND.md"),
              ("phase_r", "Phase R: reader benchmark, steering, swaps, text arms, §-series (18–26 Oct)", "BRIEF_R.md and r/* briefs")]


def cell(text, limit=None):
    if isinstance(text, (list, tuple)):
        text = ", ".join(map(str, text))
    elif isinstance(text, dict):
        text = "; ".join(f"{k}: {v}" for k, v in text.items())
    text = " ".join(str(text or "").split()).replace("|", "\\|")
    return text if limit is None or len(text) <= limit else text[:limit - 1].rstrip() + "…"


def main():
    items = json.loads((HERE / "inventory/experiments_index.json").read_text())
    lines = ["# Experiments, one line each", "",
             "Generated by `share/build_index.py` from `share/inventory/experiments_index.json`. The JSON has every field",
             "in full: hypothesis, readers and layers, item bank, n, scoring, code, results, logs, GPU time and",
             "pre-registration. Headlines here are cut at 220 characters.",
             "",
             "Paths are relative to the repo root on the branch shown; read them with",
             "`git show origin/<branch>:<path>`. Headline numbers are copied from each experiment's own results file,",
             "not recomputed. Status values: DONE, INCOMPLETE, CLOSED_INCOMPLETE (stopped with partial data, reported",
             "as such), ABANDONED, SUPERSEDED, RUNNING, QUEUED.", ""]
    for key, title, brief in PROGRAMMES:
        rows = [x for x in items if x["programme"] == key]
        lines += [f"## {title}", "", f"Pre-registrations: `projects/g_agreement/{brief}`" if "BRIEF" in brief else brief, "",
                  "| id | question | status | headline | branch | results |", "|---|---|---|---|---|---|"]
        for x in rows:
            lines.append(f"| {cell(x['id'])} | {cell(x['question'])} | {x['status']} | "
                         f"{cell(x['verdict_or_headline'], 220)} | `{cell(x['branch'], 60)}` | {cell(x['results'], 160)} |")
        lines.append("")
    (HERE / "EXPERIMENTS.md").write_text("\n".join(lines) + "\n")
    print(len(items), "experiments")


if __name__ == "__main__":
    main()
